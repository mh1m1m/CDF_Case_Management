#!/usr/bin/env node
// Writes a reviewable snapshot of the database access model (RLS state, policies, grants, definer
// functions) to infrastructure/supabase/policies/policy-snapshot.md. CI regenerates it and fails if the
// committed copy differs, so every access-model change is visible in the pull request diff (§18, §88).
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const url = process.env.CDF_ADMIN_DATABASE_URL ?? "postgresql://postgres@127.0.0.1:54322/postgres";
const schemas =
  "'core','iam','authz','audit','case_mgmt','intake','protected_identity','workflow','evidence','forms','config','api','public_api'";

// Fields are separated by the ASCII unit separator so a literal "|" inside a policy expression can be
// escaped for the Markdown table instead of being mistaken for a column boundary.
const FIELD_SEPARATOR = "\u001f";
const q = (sql) =>
  execFileSync("psql", ["--no-psqlrc", "-At", "-F", FIELD_SEPARATOR, "-d", url, "-c", sql], {
    encoding: "utf8",
  }).trim();
// Backslashes are escaped first so an escaped pipe cannot be un-escaped by a preceding literal backslash.
const cell = (value) => value.replace(/\\/g, "\\\\").replace(/\|/g, "\\|").replace(/`/g, "'");

const sections = [
  [
    "Row-level security",
    "| table | rls enabled | rls forced |",
    `select n.nspname||'.'||c.relname, c.relrowsecurity, c.relforcerowsecurity from pg_class c join pg_namespace n on n.oid=c.relnamespace
     where c.relkind in ('r','p') and n.nspname in (${schemas}) order by 1`,
  ],
  [
    "Policies",
    "| table | policy | command | roles | using |",
    `select schemaname||'.'||tablename, policyname, cmd, array_to_string(roles, ','), regexp_replace(coalesce(qual,''), '\\s+', ' ', 'g')
     from pg_policies where schemaname in (${schemas}) order by 1, 2`,
  ],
  [
    "Table privileges for application roles",
    "| grantee | table | privilege |",
    `select grantee, table_schema||'.'||table_name, privilege_type from information_schema.role_table_grants
     where grantee in ('anon','authenticated','cdf_bff','cdf_portal') and table_schema in (${schemas}) order by 1, 2, 3`,
  ],
  [
    "Column privileges (column-limited grants)",
    "| grantee | table | columns |",
    `select grantee, table_schema||'.'||table_name, string_agg(column_name, ', ' order by column_name)
     from information_schema.column_privileges
     where grantee in ('anon','authenticated') and table_schema in (${schemas})
       and (table_schema, table_name) not in (select table_schema, table_name from information_schema.role_table_grants where grantee in ('anon','authenticated'))
     group by 1, 2 order by 1, 2`,
  ],
  [
    "Functions executable by application roles",
    "| function | security definer | anon | authenticated |",
    `select p.oid::regprocedure::text, p.prosecdef, has_function_privilege('anon', p.oid, 'EXECUTE'), has_function_privilege('authenticated', p.oid, 'EXECUTE')
     from pg_proc p join pg_namespace n on n.oid=p.pronamespace
     where n.nspname in (${schemas}) and (has_function_privilege('anon', p.oid, 'EXECUTE') or has_function_privilege('authenticated', p.oid, 'EXECUTE'))
     order by 1`,
  ],
  [
    "Login roles",
    "| role | inherit | member of |",
    `select r.rolname, r.rolinherit, coalesce(string_agg(g.rolname, ',' order by g.rolname), '') from pg_roles r
     left join pg_auth_members m on m.member=r.oid left join pg_roles g on g.oid=m.roleid
     where r.rolname in ('cdf_bff','cdf_portal') group by 1, 2 order by 1`,
  ],
];

let md =
  "# Database access-model snapshot\n\nGenerated by `pnpm db:policies` from a database built with `pnpm db:reset`. Do not edit by hand.\n";
for (const [title, header, sql] of sections) {
  const rows = q(sql).split("\n").filter(Boolean);
  const cols = header.split("|").length - 2;
  md += `\n## ${title}\n\n${header}\n|${" --- |".repeat(cols)}\n`;
  for (const row of rows) md += `| ${row.split(FIELD_SEPARATOR).map(cell).join(" | ")} |\n`;
}
const out = join(root, "infrastructure", "supabase", "policies", "policy-snapshot.md");
writeFileSync(out, md);
console.log(`✓ wrote ${out.slice(root.length + 1)}`);
